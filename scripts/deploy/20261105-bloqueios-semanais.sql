-- Migração aditiva, manual e única; não é executada durante o boot.
-- Exige confirmação explícita do banco conectado via parâmetro de sessão:
-- PGOPTIONS='-c courttime.migration_database=NOME_CONFERIDO' psql ... -v ON_ERROR_STOP=1 -f ESTE_ARQUIVO
-- Revisar e testar em cópia isolada antes de autorizar qualquer aplicação no Neon.
BEGIN;
DO $$
BEGIN
    IF nullif(current_setting('courttime.migration_database', true), '')
            IS DISTINCT FROM current_database() THEN
        RAISE EXCEPTION 'Migração recusada: confira current_database() e confirme o banco na sessão';
    END IF;
END $$;
SET LOCAL search_path = public;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.bloqueios_semanais_quadra (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quadra_id bigint NOT NULL REFERENCES public.quadras(id),
    dia_semana varchar(10) NOT NULL,
    horario_inicio time(6) NOT NULL,
    horario_fim time(6) NOT NULL,
    vigencia_inicio date NOT NULL,
    vigencia_fim date NOT NULL,
    motivo varchar(200) NOT NULL,
    ativo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_bloqueio_semanal_dia CHECK
        (dia_semana IN ('SEGUNDA', 'TERCA', 'QUARTA', 'QUINTA', 'SEXTA', 'SABADO', 'DOMINGO')),
    CONSTRAINT ck_bloqueio_semanal_horarios CHECK (horario_inicio < horario_fim),
    CONSTRAINT ck_bloqueio_semanal_vigencia CHECK (vigencia_inicio <= vigencia_fim),
    CONSTRAINT ck_bloqueio_semanal_motivo CHECK (length(trim(motivo)) > 0)
);
CREATE INDEX idx_bloqueios_semanais_quadra_dia
    ON public.bloqueios_semanais_quadra (quadra_id, dia_semana);
COMMIT;
